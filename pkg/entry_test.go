package rpmdb

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func Test_headerImport(t *testing.T) {
	tests := []struct {
		name string
		data []byte
	}{
		{
			// found by fuzzer
			name: "negative il",
			data: []byte{0xe3, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30},
		},
		{
			// A zeroed region trailer leaves ril at 0, so the region slice
			// blob.peList[1:ril] was built with a high bound below its low one.
			name: "region trailer gives a zero region index length",
			data: []byte{0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x3f, 0x00, 0x00, 0x00, 0x07, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.NotPanics(t, func() {
				_, _ = headerImport(tt.data)
			})
		})
	}
}
